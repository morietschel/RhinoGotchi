<#
Generates src/RhinoGotchi/Content/ToolbarMap.g.cs: where each Command Library command's button
lives in Rhino's default toolbars, so the panel can show "where it is" and draw that toolbar.

Source: a Rhino default.rui (XML). Rhino 8 doesn't store its default layout as a readable file,
so this reads the Rhino 7 one; the Transform, Curve Tools, Solid Tools tabs and the Main sidebar
carry over to Rhino 8 for these commands.

  pwsh tools/Generate-ToolbarMap.ps1 [-Rui <path to default.rui>]
#>
param(
    [string]$Rui = (Join-Path $env:APPDATA 'McNeel\Rhinoceros\7.0\UI\default.rui')
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$catalog = Join-Path $repo 'src\RhinoGotchi\Content\CommandCatalog.cs'
$out = Join-Path $repo 'src\RhinoGotchi\Content\ToolbarMap.g.cs'

[xml]$x = Get-Content $Rui -Raw
function Text($n) { $n.SelectSingleNode('*[local-name()="text"]/*[local-name()="locale_1033"]').InnerText }
function Child($n, $name) { $n.SelectSingleNode("*[local-name()=""$name""]") }
function FirstCommand($script) {
    if (-not $script) { return '' }
    $tok = ($script -replace '^\s*!?\s*', '' -split '[\s;]+')[0]
    return ($tok -replace '^[_\-]+', '')
}

$macro = @{}; $macroTip = @{}
foreach ($m in $x.SelectNodes('//*[local-name()="macro_item"]')) { $macro[$m.guid] = (Child $m 'script').InnerText; $macroTip[$m.guid] = Text $m }
$toolbars = @{}
foreach ($tb in $x.SelectNodes('//*[local-name()="tool_bar"]')) { $toolbars[$tb.guid] = $tb }

# Roots a learner sees: three Standard tabs plus the Main sidebar. Value = label shown in the panel.
$roots = [ordered]@{ 'Transform' = 'Transform tab'; 'Curve Tools' = 'Curve Tools tab'; 'Solid Tools' = 'Solid Tools tab'; 'Main' = 'Main sidebar (left)' }
$rootIds = [ordered]@{}
foreach ($name in $roots.Keys) {
    $tb = $toolbars.Values | Where-Object { (Text $_) -eq $name } | Select-Object -First 1
    if (-not $tb) { throw "Toolbar '$name' not found in $Rui" }
    $rootIds[$name] = $tb.guid
}

function Buttons($tb) {
    foreach ($item in $tb.SelectNodes('*[local-name()="tool_bar_item"]')) {
        $lm = (Child $item 'left_macro_id').InnerText
        $script = if ($lm) { $macro[$lm] } else { '' }
        # Rhino shows the left macro's text as the tooltip; the item's own text is often a stale label.
        $tip = if ($lm -and $macroTip[$lm]) { $macroTip[$lm] } else { Text $item }
        [pscustomobject]@{
            Tip     = $tip
            Command = (FirstCommand $script)
            Link    = (Child $item 'link').InnerText
        }
    }
}

$commands = [regex]::Matches((Get-Content $catalog -Raw), '"([A-Za-z0-9]+)\|') | ForEach-Object { $_.Groups[1].Value } | Where-Object { $_ -ne 'Command' }
$strips = [ordered]@{}   # toolbar name -> button tooltips
$locations = [ordered]@{}

foreach ($rootName in $rootIds.Keys) {
    $rootButtons = @(Buttons $toolbars[$rootIds[$rootName]])
    for ($i = 0; $i -lt $rootButtons.Count; $i++) {
        $b = $rootButtons[$i]
        if ($commands -contains $b.Command -and -not ($locations[$b.Command] -match "`"$rootName`"")) {
            $strips[$rootName] = $rootButtons.Tip
            if (-not $locations[$b.Command]) { $locations[$b.Command] = @() }
            $locations[$b.Command] += "new ToolbarSpot(`"$rootName`", $i, null, -1)"
        }
        if ($b.Link -and $toolbars[$b.Link]) {
            $fly = $toolbars[$b.Link]
            $flyName = Text $fly
            $flyButtons = @(Buttons $fly)
            for ($j = 0; $j -lt $flyButtons.Count; $j++) {
                $c = $flyButtons[$j].Command
                if ($commands -contains $c -and -not ($locations[$c] -match "`"$rootName`"")) {
                    $strips[$rootName] = $rootButtons.Tip
                    $strips[$flyName] = $flyButtons.Tip
                    if (-not $locations[$c]) { $locations[$c] = @() }
                    $locations[$c] += "new ToolbarSpot(`"$rootName`", $i, `"$flyName`", $j)"
                }
            }
        }
    }
}

function Q($s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }
$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated> by tools/Generate-ToolbarMap.ps1 from Rhino''s default.rui. Do not edit by hand. </auto-generated>')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace RhinoGotchi.Content')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal static partial class ToolbarMap')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        /// <summary>Label shown for each root toolbar.</summary>')
[void]$sb.AppendLine('        public static readonly Dictionary<string, string> RootLabels = new Dictionary<string, string>')
[void]$sb.AppendLine('        {')
foreach ($k in $roots.Keys) { [void]$sb.AppendLine("            [$(Q $k)] = $(Q $roots[$k]),") }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>Button tooltips, in order, for each toolbar the panel can draw.</summary>')
[void]$sb.AppendLine('        public static readonly Dictionary<string, string[]> Toolbars = new Dictionary<string, string[]>')
[void]$sb.AppendLine('        {')
foreach ($k in $strips.Keys) { [void]$sb.AppendLine("            [$(Q $k)] = new[] { $((@($strips[$k]) | ForEach-Object { Q $_ }) -join ', ') },") }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>Where each command''s button is: root toolbar and button, and optionally a flyout and its button.</summary>')
[void]$sb.AppendLine('        public static readonly Dictionary<string, ToolbarSpot[]> Locations = new Dictionary<string, ToolbarSpot[]>(System.StringComparer.OrdinalIgnoreCase)')
[void]$sb.AppendLine('        {')
foreach ($k in $locations.Keys) { [void]$sb.AppendLine("            [$(Q $k)] = new[] { $($locations[$k] -join ', ') },") }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
Set-Content -Path $out -Value $sb.ToString() -Encoding UTF8

"Wrote $out"
"Commands located: $($locations.Count) of $($commands.Count)"
"Not found: " + (($commands | Where-Object { -not $locations.Contains($_) }) -join ', ')
